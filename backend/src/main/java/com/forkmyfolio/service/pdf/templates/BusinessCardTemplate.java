package com.forkmyfolio.service.pdf.templates;

import com.forkmyfolio.model.PortfolioProfile;
import com.forkmyfolio.model.User;
import com.forkmyfolio.service.impl.PdfGenerationService;
import com.forkmyfolio.service.pdf.PortfolioData;
import com.forkmyfolio.service.pdf.QrCodeImages;
import org.openpdf.text.Chunk;
import org.openpdf.text.Document;
import org.openpdf.text.DocumentException;
import org.openpdf.text.Element;
import org.openpdf.text.Font;
import org.openpdf.text.Image;
import org.openpdf.text.Paragraph;
import org.openpdf.text.Rectangle;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;

import java.awt.Color;
import java.io.IOException;

/**
 * Phase 0.12 (OpenPDF migration): the QR code is a bitmap generated by
 * {@link QrCodeImages} (ZXing) — the previous engine rendered a vector form
 * XObject and OpenPDF 3.x ships no QR support. The full-height two-column
 * layout is a {@link PdfPTable} whose cells stretch to the printable page
 * height (144pt page − 2×18pt margins = 108pt) so the vertical-middle
 * alignment behaves exactly as before.
 */
public class BusinessCardTemplate implements PortfolioPdfTemplate {

    @Override
    public Rectangle getPageSize() {
        // Standard US business card: 3.5 x 2 inches. 1 inch = 72 points.
        return new Rectangle(3.5f * 72, 2f * 72);
    }

    @Override
    public float[] getMargins() {
        // Previous engine: setMargins(18, 18, 18, 18) — 0.25 inch margins
        return new float[]{18, 18, 18, 18}; // {left, right, top, bottom}
    }

    @Override
    public void generate(Document document, PdfGenerationService.PdfContext ctx, PortfolioData data)
            throws IOException, DocumentException {
        PortfolioProfile profile = data.profile();
        User user = profile.getUser();

        PdfPTable mainTable = new PdfPTable(new float[]{3, 2});
        mainTable.setWidthPercentage(100);
        float contentHeight = getPageSize().getHeight() - 18 - 18; // page height minus margins

        // Left side: Text info
        PdfPCell leftCell = new PdfPCell();
        leftCell.setBorder(Rectangle.NO_BORDER);
        leftCell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        leftCell.setMinimumHeight(contentHeight);

        Paragraph nameLine = new Paragraph(user.getFirstName() + " " + user.getLastName(),
                new Font(ctx.nameFont, 14, Font.NORMAL, Color.BLACK));
        nameLine.setLeading(0, 1.4f);
        nameLine.setSpacingAfter(2);
        leftCell.addElement(nameLine);
        Paragraph headlineLine = new Paragraph(profile.getHeadline(),
                new Font(ctx.itemSubtitleFont, 8, Font.NORMAL, PdfGenerationService.SECONDARY_COLOR));
        headlineLine.setLeading(0, 1.4f);
        headlineLine.setSpacingAfter(10);
        leftCell.addElement(headlineLine);

        // Phase 8.3: the contact lines honour the owner's export contact
        // toggle; the email shown is the export data's contactEmail
        // (publicEmail for public exports, publicEmail-or-account-email for
        // owner exports — parity with the Markdown export).
        if (data.includeContact() && data.contactEmail() != null && !data.contactEmail().isBlank()) {
            Paragraph emailLine = new Paragraph(data.contactEmail(),
                    new Font(ctx.bodyFont, 7, Font.NORMAL, Color.BLACK));
            emailLine.setLeading(0, 1.4f);
            leftCell.addElement(emailLine);
        }

        // --- Make website URL a clickable link ---
        if (data.includeContact() && profile.getWebsiteUrl() != null && !profile.getWebsiteUrl().isBlank()) {
            String cleanUrl = profile.getWebsiteUrl().replaceFirst("^(https?://)", "");
            Chunk linkChunk = new Chunk(cleanUrl,
                    new Font(ctx.bodyFont, 7, Font.NORMAL, PdfGenerationService.ACCENT_COLOR));
            linkChunk.setAnchor(profile.getWebsiteUrl());
            linkChunk.setUnderline(1f, -2);
            Paragraph linkLine = new Paragraph(linkChunk);
            linkLine.setLeading(0, 1.4f);
            leftCell.addElement(linkLine);
        }
        mainTable.addCell(leftCell);

        // Right side: QR Code
        PdfPCell rightCell = new PdfPCell();
        rightCell.setBorder(Rectangle.NO_BORDER);
        rightCell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        rightCell.setHorizontalAlignment(Element.ALIGN_RIGHT);
        rightCell.setMinimumHeight(contentHeight);
        if (profile.getWebsiteUrl() != null && !profile.getWebsiteUrl().isBlank()) {
            // 1x1 inch QR code
            Image qrImage = QrCodeImages.createQrImage(profile.getWebsiteUrl(), Color.BLACK, 72);
            rightCell.addElement(qrImage);
        }
        mainTable.addCell(rightCell);

        document.add(mainTable);
    }
}
